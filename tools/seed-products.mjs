// Writes supabase/seed.sql from the catalog in store/js/data.js (every product, flagged ones included).
// Run after changing data.js:  node tools/seed-products.mjs   then run seed.sql in the Supabase SQL Editor.
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';

const root = new URL('../', import.meta.url);
const window = {};
vm.runInNewContext(readFileSync(new URL('store/js/data.js', root), 'utf8'), { window });
const { products } = window.PS;

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const json = (v) => `${q(JSON.stringify(v))}::jsonb`;
const rows = products.map((p, i) => {
  const { id, name, cat, sizes, cardsAllowed, ...details } = p;
  return `  (${q(id)}, ${q(name)}, ${q(cat)}, ${json(sizes)}, ${cardsAllowed !== false}, ${i}, ${json(details)})`;
});

writeFileSync(new URL('supabase/seed.sql', root), `-- Generated by tools/seed-products.mjs from store/js/data.js. Don't edit by hand.
-- Adds or updates every product; products removed from data.js are left alone (set active = false to hide one).
insert into public.products (id, name, category, sizes, cards_allowed, sort, details) values
${rows.join(',\n')}
on conflict (id) do update set
  name = excluded.name, category = excluded.category, sizes = excluded.sizes, cards_allowed = excluded.cards_allowed,
  sort = excluded.sort, details = excluded.details, updated_at = now();
`);
console.log(`supabase/seed.sql: ${rows.length} products`);
